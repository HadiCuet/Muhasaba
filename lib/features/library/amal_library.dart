/// A ready-made amal in the Amal Library.
///
/// [title] is canonical English, stored verbatim in `amals.title` and
/// translated at display time by `localizedAmalTitle`, like the seeded amals.
class LibraryAmal {
  const LibraryAmal({
    required this.key,
    required this.icon,
    required this.title,
    required this.category,
    this.frequency = Frequency.daily,
    this.weeklyDays = const <int>{},
    this.periodTarget = 1,
    this.target = 1,
  });

  /// Stable id for analytics; never shown or stored.
  final String key;
  final String icon;
  final String title;
  final String category;
  final Frequency frequency;

  /// Pinned weekdays (Mon=1). Empty on a weekly amal means any day.
  final Set<int> weeklyDays;

  /// Days per week or month for an amal that isn't pinned to set days.
  final int periodTarget;

  /// Count per day; [kOpenEndedTarget] means any amount.
  final int target;
}

